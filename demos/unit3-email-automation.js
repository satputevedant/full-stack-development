const nodemailer = require('nodemailer');

async function sendEmergencyAlert(incidentDetails) {
  console.log('=== Unit 3 Demo: Automated Email Notification ===');

  // Generate simulated test account on Ethereal
  console.log('Generating test email account...');
  const testAccount = await nodemailer.createTestAccount();

  const transporter = nodemailer.createTransport({
    host: testAccount.smtp.host,
    port: testAccount.smtp.port,
    secure: testAccount.smtp.secure,
    auth: {
      user: testAccount.user,
      pass: testAccount.pass
    }
  });

  const mailOptions = {
    from: '"EMS Command Center" <dispatch@emergency-system.local>',
    to: incidentDetails.hospitalEmail || 'hospital-trauma@healthcare.org',
    subject: `🚨 [IMMEDIATE TRAUMA ALERT] Incident #${incidentDetails.id} Inbound`,
    text: `Incoming Critical Patient: ${incidentDetails.type}. Location: ${incidentDetails.address}. ETA: 4 minutes.`,
    html: `
      <div style="font-family: sans-serif; background: #0D1117; color: #FFF; padding: 20px; border-radius: 8px;">
        <h2 style="color: #FF453A;">🚨 Emergency Healthcare Response Dispatch Alert</h2>
        <p><strong>Incident ID:</strong> #${incidentDetails.id}</p>
        <p><strong>Condition:</strong> ${incidentDetails.type} (${incidentDetails.severity})</p>
        <p><strong>Location:</strong> ${incidentDetails.address}</p>
        <p><strong>Assigned Unit:</strong> ${incidentDetails.unit} (ETA: ${incidentDetails.etaMin} mins)</p>
        <hr style="border-color: #30363D;" />
        <small style="color: #8B949E;">Automated dispatch notification generated by EmergencyDispatchApp Node.js service.</small>
      </div>
    `
  };

  console.log('Dispatching automated notification email...');
  const info = await transporter.sendMail(mailOptions);

  console.log('✓ Email Sent Successfully!');
  console.log('Message ID:', info.messageId);
  console.log('Preview URL (Ethereal Web Viewer):', nodemailer.getTestMessageUrl(info));
  return info;
}

if (require.main === module) {
  sendEmergencyAlert({
    id: 101,
    type: 'Cardiac Arrest',
    severity: 'Critical',
    address: '42 Elm Street, Central Zone',
    unit: 'AMB-101',
    etaMin: 4
  }).catch(console.error);
}

module.exports = sendEmergencyAlert;
